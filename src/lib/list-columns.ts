/**
 * @file list-columns.ts
 * @description Раскладка карточек списков по колонкам.
 *
 * Колонки собираются вручную, а не средствами `columns` или грида, потому что
 * обе автоматические раскладки конфликтуют со сворачиванием карточки:
 *
 *   - в multicol колонка карточки вычисляется из высот содержимого, поэтому
 *     изменение высоты одной карточки перебрасывало соседей между колонками;
 *   - в гриде ряды выровнены по горизонтали, поэтому рядом со свёрнутой
 *     карточкой оставалась пустота во всю высоту раскрытой соседки.
 *
 * Здесь колонка определяется порядковым номером карточки и от высот не зависит
 * вовсе, а внутри колонки карточки лежат вплотную.
 */

/**
 * Разбивает список на колонки подряд идущими кусками.
 *
 * Кусками, а не по остатку от деления: так сохраняется порядок чтения сверху
 * вниз по колонке — тот же, что был в multicol, — и соседи по вертикали
 * остаются соседями по номеру. Последнее понадобится, когда карточки можно
 * будет перетаскивать: «бросил между этими двумя» превратится в соседний
 * индекс, а не в вычисление задом наперёд.
 *
 * Размеры колонок различаются не больше чем на единицу: остаток раздаётся
 * первым колонкам, иначе последняя оказывалась бы почти пустой.
 *
 * Высоты карточек не учитываются намеренно — именно эта независимость и
 * убирает перестроения при сворачивании. Плата за неё в том, что колонки
 * заканчиваются на разной высоте.
 *
 * @param items - Карточки в порядке отображения.
 * @param columnCount - Число колонок; меньше единицы трактуется как одна.
 */
export function splitIntoColumns<T>(items: T[], columnCount: number): T[][] {
  const count = Math.max(1, Math.floor(columnCount));
  const base = Math.floor(items.length / count);
  const remainder = items.length % count;

  const columns: T[][] = [];
  let offset = 0;
  for (let index = 0; index < count; index += 1) {
    const size = base + (index < remainder ? 1 : 0);
    columns.push(items.slice(offset, offset + size));
    offset += size;
  }
  return columns;
}
