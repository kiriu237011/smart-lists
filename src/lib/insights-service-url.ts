/**
 * @file insights-service-url.ts
 * @description Проверка адреса AI-сервиса перед исходящим запросом.
 *
 * Зачем: `INSIGHTS_SERVICE_URL` задаёт, кому уйдёт содержимое списка — заголовок,
 * записи и заметки. До этой проверки значение использовалось как есть, поэтому
 * одна строка в настройках Vercel перенаправляла весь поток на произвольный хост.
 * Опасна не подмена сама по себе — сделать её может только владелец проекта,
 * который и так может выложить любой код, — а то, что она не оставляет следа
 * там, где его стали бы искать: значение переменной не лежит в git, не проходит
 * ревью и не проходит CI. Egress-контейнмента на Vercel нет и быть не может
 * (A69), поэтому сеть такой запрос не остановит: барьер существует только здесь.
 *
 * Это зеркало уже закрытого остатка A56 в FastAPI-сервисе, где ровно так же
 * `ANTHROPIC_BASE_URL` уводил поток вместе с токеном. Там адрес прибит в коде;
 * здесь прибить нельзя — он различается между окружениями и меняется при
 * пересоздании сервиса, — поэтому проверяется форма.
 *
 * Чего проверка НЕ даёт: перенаправление на другой Cloud Run того же владельца
 * остаётся возможным. Убирается произвольный хост, то есть собственно путь утечки.
 */

/** Cloud Run отдаёт сервисы только на этом домене. */
const EXPECTED_HOST_SUFFIX = ".run.app";

/**
 * Имя сервиса из `deploy.yml`. Обе живые формы адреса — `insights-api-<номер
 * проекта>.<регион>.run.app` и `insights-api-<хеш>-uc.a.run.app` — начинаются
 * с него, поэтому префикса достаточно и он не завязан на конкретный регион.
 */
const EXPECTED_SERVICE_PREFIX = "insights-api-";

/**
 * Приводит значение переменной окружения к базовому URL сервиса.
 *
 * @param raw сырое значение `INSIGHTS_SERVICE_URL`.
 * @returns origin без завершающего слэша либо `null`, если адрес не является
 *   адресом ожидаемого сервиса Cloud Run.
 *
 * Возврат `null` вместо исключения выбран, чтобы результат совпал с уже
 * существующим fail-closed путём «переменная не задана»: вызывающий отвечает
 * `Service not configured`, запрос не уходит и квота пользователя не списывается.
 */
export function resolveInsightsServiceUrl(
  raw: string | undefined | null,
): string | null {
  if (!raw) return null;

  let url: URL;
  try {
    url = new URL(raw);
  } catch {
    return null;
  }

  // TLS обязателен: без него содержимое списка уехало бы открытым текстом.
  if (url.protocol !== "https:") return null;

  // `https://insights-api-x.run.app@evil.example` парсится как логин на чужом
  // хосте. Проверка hostname прошла бы, поэтому credentials запрещены отдельно.
  if (url.username !== "" || url.password !== "") return null;

  // Порт, query и fragment у базового адреса сервиса взяться неоткуда; их
  // наличие означает, что значение собрано не из того, из чего ожидалось.
  if (url.port !== "") return null;
  if (url.search !== "" || url.hash !== "") return null;

  // `new URL` нормализует пустой путь в "/", поэтому это и есть «пути нет».
  if (url.pathname !== "/") return null;

  const host = url.hostname.toLowerCase();

  // Суффикс проверяется концом строки, а не вхождением: `run.app.evil.example`
  // содержит `.run.app`, но принадлежит атакующему.
  if (!host.endsWith(EXPECTED_HOST_SUFFIX)) return null;
  if (!host.startsWith(EXPECTED_SERVICE_PREFIX)) return null;

  return url.origin;
}
