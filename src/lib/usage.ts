/**
 * @file usage.ts
 * @description Суточные счётчики пользователя: бюджет мутаций и уборка истории.
 *
 * Зачем нужен бюджет. Потолки из `@/lib/limits` ограничивают размер одного
 * контейнера, но не темп: переключать отметку у одного пункта можно
 * бесконечно, ничего не создавая, и каждый такой вызов — запрос к Neon и
 * событие Pusher. Бюджет ограничивает именно темп и потому закрывает то, чего
 * потолки не закрывают: рост хранилища в целом, расход compute и квоту
 * сообщений Pusher.
 *
 * Почему в БД, а не в памяти процесса. Vercel исполняет Server Actions в
 * нескольких изолированных экземплярах, и счётчик в памяти считал бы каждый
 * своё. Та же ошибка уже разбиралась в модели угроз применительно к SlowAPI на
 * Cloud Run: лимит, размазанный по инстансам, растёт вместе с нагрузкой —
 * то есть отказывает ровно тогда, когда нужен.
 *
 * Цена — одна запись в БД на мутацию. Она заметна на фоне 1–3 запросов
 * обычного действия, и это осознанный размен: мера против нагрузки сама
 * создаёт нагрузку, но ограниченную и предсказуемую.
 */

import prisma from "@/lib/db";
import { logger, hashId } from "@/lib/logger";

/**
 * Потолок мутаций на пользователя в сутки.
 *
 * Выбран так, чтобы человек его не встретил: активный день ручной работы со
 * списками — это десятки действий, редко сотни. Зациклившийся клиент выбирает
 * тысячу за минуты, и в этом вся разница между «пользуется» и «сломалось».
 */
export const DAILY_MUTATION_LIMIT = 1000;

/**
 * Сколько суток хранятся ряды счётчиков.
 *
 * Самой квоте история не нужна — она читает только сегодняшний ряд. История
 * нужна ровно на один вопрос: «почему вчера кончился лимит». Тридцать суток
 * совпадают с горизонтом бэкапов и noncurrent-версий в S3.
 */
export const USAGE_RETENTION_DAYS = 30;

/** Текущая дата, нормализованная до UTC-полуночи. */
export function usageDate(now: Date = new Date()): Date {
  const date = new Date(now);
  date.setUTCHours(0, 0, 0, 0);
  return date;
}

/**
 * Удаляет ряды старше срока хранения.
 *
 * Уборка ленивая — без крона и без отдельного входа в систему, который
 * пришлось бы заносить в модель угроз. Тот же приём, что чистит зависшие
 * `PENDING`-вложения в `requestUpload`.
 *
 * Вызывается не на каждой мутации: это была бы лишняя запись в каждом
 * запросе — ровно та нагрузка, которую бюджет и ограничивает. Вызов идёт один
 * раз в сутки на пользователя, в момент, когда суточный ряд только появился.
 *
 * Чистятся только ряды самого пользователя. Уборка «за всех» под нагрузкой
 * превратилась бы в длинный DELETE у случайного человека, которому просто не
 * повезло зайти первым.
 */
async function pruneOwnUsage(userId: string, today: Date): Promise<void> {
  const threshold = new Date(
    today.getTime() - USAGE_RETENTION_DAYS * 24 * 60 * 60 * 1000,
  );

  const { count } = await prisma.userDailyUsage.deleteMany({
    where: { userId, date: { lt: threshold } },
  });

  if (count > 0) {
    logger.info(
      { uid: hashId(userId), count, action: "usage.prune" },
      "Прибраны старые ряды суточных счётчиков",
    );
  }
}

/**
 * Списывает одну мутацию из суточного бюджета.
 *
 * Возвращает `true`, если действие разрешено, и `false`, если бюджет исчерпан.
 *
 * Инкремент атомарен: `upsert` с `increment` держит row lock на уникальном
 * ключе (userId, date), поэтому параллельные запросы получают строго
 * возрастающие значения. Раздельные `findUnique` и `update` оставляли бы окно
 * TOCTOU, через которое пачка одновременных запросов проскакивала бы проверку
 * при нулевом счётчике — та же ошибка была исправлена в квоте инсайтов.
 *
 * При переборе инкремент откатывается: иначе отвергнутые попытки съедали бы
 * бюджет следующего дня в тот момент, когда счётчик уже никого не пускает.
 */
export async function consumeMutationBudget(userId: string): Promise<boolean> {
  const today = usageDate();

  const usage = await prisma.userDailyUsage.upsert({
    where: { userId_date: { userId, date: today } },
    update: { mutations: { increment: 1 } },
    create: { userId, date: today, mutations: 1 },
    select: { mutations: true, insights: true },
  });

  // Ряд создан этим вызовом: за сегодня учтено ровно одно событие, и оно наше.
  // Значит наступили новые сутки — подходящий момент для уборки.
  if (usage.mutations === 1 && usage.insights === 0) {
    await pruneOwnUsage(userId, today).catch((error) => {
      // Сбой уборки не должен отменять действие пользователя: она —
      // гигиена, а не часть контракта. Следующие сутки дадут новый шанс.
      logger.error({ error, action: "usage.prune" }, "Уборка счётчиков не удалась");
    });
  }

  if (usage.mutations > DAILY_MUTATION_LIMIT) {
    await prisma.userDailyUsage
      .update({
        where: { userId_date: { userId, date: today } },
        data: { mutations: { decrement: 1 } },
      })
      .catch((error) => {
        // Счётчик останется завышенным на единицу до конца суток; завтра
        // будет создан новый ряд по новому ключу, и перекос исчезнет сам.
        logger.error({ error, action: "usage.rollback" }, "Откат счётчика мутаций не удался");
      });

    logger.warn(
      { uid: hashId(userId), count: usage.mutations, action: "usage.limit" },
      "Превышен суточный лимит мутаций",
    );
    return false;
  }

  return true;
}
