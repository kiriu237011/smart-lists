/**
 * @file limits.ts
 * @description Структурные потолки на количество сущностей.
 *
 * Что эти числа защищают — и чего не защищают.
 *
 * Они ограничивают **один контейнер**: список с миллионом пунктов ломает
 * интерфейс, стоимость выборки и пересчёт позиций задолго до того, как
 * кончится место в базе. Потолок держит каждый контейнер в размерах, при
 * которых приложение остаётся отзывчивым.
 *
 * Суммарный рост они не ограничивают, и считать иначе было бы ошибкой:
 * произведение потолков — миллионы строк на одного пользователя. Границу
 * хранилища задаёт суточный лимит мутаций, а не эти числа.
 *
 * Значения выбраны так, чтобы человек их не встретил: они отсекают
 * зациклившийся клиент и угнанную сессию, а не сценарий использования.
 */

// Пространства здесь намеренно отсутствуют: их потолок — `MAX_CUSTOM_SPACES`
// в `@/lib/spaces`, он появился раньше и живёт рядом с остальной логикой
// пространств. Дубль константы разошёлся бы с оригиналом при первой же правке.

/** Списков в одном пространстве. */
export const MAX_LISTS_PER_SPACE = 200;

/** Групп в одном пространстве. */
export const MAX_GROUPS_PER_SPACE = 50;

/** Пунктов верхнего уровня в списке. */
export const MAX_ITEMS_PER_LIST = 500;

/**
 * Подпунктов у одного пункта.
 *
 * Считается отдельно от пунктов верхнего уровня — по той же причине, по
 * которой раздельны лимиты AI-контекста: общий счёт означал бы разное для
 * разных списков, и один длинный блок подпунктов съедал бы место всего списка.
 */
export const MAX_SUB_ITEMS_PER_ITEM = 100;
